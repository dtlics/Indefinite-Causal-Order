def relative(path: Path) -> str:
    return path.resolve().relative_to(REPO).as_posix()


def input_hashes() -> dict[str, str]:
    """Include canonical mathematical notes as well as executable inputs."""
    files = set(TOPIC.rglob("*.md"))
    files.update(p for p in HERE.rglob("*.py") if "__pycache__" not in p.parts)
    files.update(p for p in HERE.rglob("*.json") if p != RECORD and "__pycache__" not in p.parts)
    return {relative(p): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(files) if p.is_file()}


def prepare_stage() -> Path:
    BUILD.mkdir(parents=True, exist_ok=True)
    stage = (BUILD / "stage").resolve()
    # Resolve and check the deletion target before any recursive removal.
    if (not BUILD.resolve().is_relative_to(REPO.resolve())
            or stage.parent != BUILD.resolve() or stage.name != "stage"):
        raise RuntimeError("Unsafe staging directory")
    if stage.exists():
        shutil.rmtree(stage)
    stage.mkdir()
    for source in HERE.rglob("*"):
        if not source.is_file() or source == RECORD or "__pycache__" in source.parts:
            continue
        if source.suffix not in (".py", ".json"):
            continue
        target = stage / source.relative_to(HERE)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, target)
    return stage


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--record", action="store_true",
                        help="Replace the single tracked validation record after successful stable replay")
    args = parser.parse_args()
    if not sys.flags.no_site:
        # Make the documented standard-library-only environment automatic.
        return subprocess.run([sys.executable, "-S", str(Path(__file__).resolve()),
                               *sys.argv[1:]], check=False).returncode
    before = input_hashes()
    stage = prepare_stage()
    logs = BUILD / "logs"
    logs.mkdir(exist_ok=True)
    env = os.environ.copy()
    for key in ("PYTHONPATH", "PYTHONOPTIMIZE"):
        env.pop(key, None)
    env["PYTHONDONTWRITEBYTECODE"] = "1"
    env["PYTHONNOUSERSITE"] = "1"
    started = time.monotonic()
    jobs = []
    for name, source, arguments, scope in JOBS:
        command = [sys.executable, "-S", "-B", str(stage / source)]
        command.extend(str(stage / a) if a.endswith(".json") else a for a in arguments)
        result = subprocess.run(command, cwd=stage, env=env, text=True,
                                encoding="utf-8", errors="strict", capture_output=True,
                                check=False)
        log = logs / (name + ".log")
        log.write_text(result.stdout + ("\nSTDERR:\n" + result.stderr if result.stderr else ""),
                       encoding="utf-8")
        data = None
        if result.returncode == 0:
            try:
                data = json.loads(result.stdout)
            except json.JSONDecodeError:
                pass
        passed = result.returncode == 0 and isinstance(data, dict) and data.get("status") == "passed"
        jobs.append({"id": name, "source": "research/topics/nr-noisy-recovery/checks/" + source,
                     "scope": scope, "outcome": "passed" if passed else "failed",
                     "exit_code": result.returncode, "log": relative(log)})
        print(name + ": " + jobs[-1]["outcome"], flush=True)
        if not passed:
            print("See " + relative(log), flush=True)
            break
    after = input_hashes()
    stable = before == after
    passed = len(jobs) == len(JOBS) and all(j["outcome"] == "passed" for j in jobs) and stable
    record = {
        "schema": SCHEMA,
        "outcome": "passed" if passed else "failed",
        "generated_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "command": "python -S research/topics/nr-noisy-recovery/checks/run_all.py" + (" --record" if args.record else ""),
        "environment": {"python": platform.python_version(), "implementation": platform.python_implementation(),
                        "operating_system": platform.system(), "site_disabled": bool(sys.flags.no_site),
                        "optimization": sys.flags.optimize, "third_party_dependencies": []},
        "input_hash_algorithm": "sha256", "input_hashes": before,
        "input_scope": "All topic Markdown notes and required Python/certificate JSON inputs; this validation record excluded.",
        "inputs_stable_during_run": stable,
        "jobs": jobs,
        "scope": SCOPE,
        "limitations": ["Analytic completeness, physical interface, stopping and norm-transfer arguments remain in the canonical proof notes.",
                        "No numerical SDP discovery, hardware experiment, novelty audit or fixed native-gate fault-tolerance claim is performed."],
    }
    report = BUILD / "report.json"
    report.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8", newline="\n")
    if passed and args.record:
        RECORD.write_text(json.dumps(record, indent=2) + "\n", encoding="utf-8", newline="\n")
    recorded = json.loads(RECORD.read_text(encoding="utf-8")) if RECORD.exists() else {}
    current = (recorded.get("schema") == SCHEMA and recorded.get("outcome") == "passed"
               and recorded.get("scope") == SCOPE and recorded.get("input_hashes") == after)
    print(json.dumps({"outcome": "passed" if passed and current else "failed",
                      "exact_replay_outcome": record["outcome"],
                      "jobs_passed": sum(j["outcome"] == "passed" for j in jobs),
                      "input_count": len(before), "inputs_stable": stable,
                      "tracked_record_current": current,
                      "record_refreshed": bool(passed and args.record), "report": relative(report),
                      "elapsed_seconds": round(time.monotonic() - started, 3)}, indent=2))
    return 0 if passed and current else 1


if __name__ == "__main__":
    raise SystemExit(main())
